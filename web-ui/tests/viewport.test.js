import { afterEach, expect, it, vi } from 'vitest'
import { mount, flushPromises } from '@vue/test-utils'
import App from '../src/App.vue'

let wrapper
const root = document.documentElement
const css = name => root.style.getPropertyValue(name)
afterEach(() => {
  wrapper?.unmount()
  wrapper = null
  vi.unstubAllGlobals()
  root.removeAttribute('style')
  root.removeAttribute('data-keyboard')
  root.removeAttribute('data-native-insets')
  root.removeAttribute('data-short-viewport')
})

it('mounts a measured viewport and tracks visual resize/scroll until unmount', async () => {
  const viewport = Object.assign(new EventTarget(), { height: 748, width: 390, offsetTop: 0, offsetLeft: 0, scale: 1 })
  vi.stubGlobal('innerHeight', 844)
  vi.stubGlobal('innerWidth', 390)
  vi.stubGlobal('visualViewport', viewport)
  wrapper = mount(App)
  await flushPromises()
  expect(css('--vvh')).toBe('748px')
  expect(css('--vvw')).toBe('390px')
  expect(root.dataset.keyboard).toBe('0') // 96px browser toolbar is not an IME.
  Object.assign(viewport, { height: 350, width: 320, offsetTop: 80, offsetLeft: 10 })
  viewport.dispatchEvent(new Event('resize'))
  expect(css('--vvh')).toBe('350px')
  expect(root.dataset.shortViewport).toBe('1')
  Object.assign(viewport, { offsetTop: 94, offsetLeft: 24 })
  viewport.dispatchEvent(new Event('scroll'))
  expect(css('--vv-top')).toBe('94px')
  expect(css('--vv-left')).toBe('24px')
  expect(css('--usable-bottom')).toBe('444px')
  wrapper.unmount()
  wrapper = null
  const afterUnmount = root.getAttribute('style')
  Object.assign(viewport, { height: 600, offsetTop: 0 })
  viewport.dispatchEvent(new Event('resize'))
  viewport.dispatchEvent(new Event('scroll'))
  window.dispatchEvent(new Event('resize'))
  expect(root.getAttribute('style')).toBe(afterUnmount)
})

it('falls back to the layout viewport without visualViewport and follows resize', async () => {
  vi.stubGlobal('visualViewport', undefined)
  vi.stubGlobal('innerHeight', 156)
  vi.stubGlobal('innerWidth', 275)
  wrapper = mount(App)
  await flushPromises()
  expect(css('--vvh')).toBe('156px')
  expect(css('--vvw')).toBe('275px')
  expect(css('--vv-top')).toBe('0px')
  expect(root.dataset.keyboard).toBe('0')
  vi.stubGlobal('innerHeight', 640)
  window.dispatchEvent(new Event('resize'))
  expect(css('--vvh')).toBe('640px')
  expect(root.dataset.shortViewport).toBe('0')
})

it('ignores invalid visual sizes and clamps overscroll offsets without writing NaN CSS', async () => {
  const viewport = Object.assign(new EventTarget(), { height: NaN, width: 0, offsetTop: -8, offsetLeft: -2, scale: 1 })
  vi.stubGlobal('innerHeight', 640)
  vi.stubGlobal('innerWidth', 390)
  vi.stubGlobal('visualViewport', viewport)
  wrapper = mount(App)
  await flushPromises()
  expect(css('--vvh')).toBe('640px')
  expect(css('--vvw')).toBe('390px')
  expect(css('--vv-top')).toBe('0px')
  expect(css('--vv-left')).toBe('0px')
  expect(css('--usable-bottom')).toBe('640px')
})

it('does not subtract already consumed Android rawIme/system bars and honors host close at a zoomed viewport', async () => {
  const viewport = Object.assign(new EventTarget(), { height: 156, width: 275, scale: 1 })
  vi.stubGlobal('innerHeight', 156)
  vi.stubGlobal('innerWidth', 275)
  vi.stubGlobal('visualViewport', viewport)
  wrapper = mount(App, { attachTo: document.body })
  await flushPromises()
  const insets = rawIme => window.dispatchEvent(new CustomEvent('studio:insets', {
    detail: { top: 0, bottom: 0, left: 0, right: 0, ime: 0, rawTop: 63, rawBottom: 63, rawIme, density: 2.625 }
  }))
  insets(780)
  expect(root.dataset.keyboard).toBe('1')
  expect(css('--vvh')).toBe('156px')
  expect(css('--native-inset-top')).toBe('0px')
  expect(css('--native-inset-bottom')).toBe('0px')
  wrapper.get('input').element.focus()
  vi.stubGlobal('innerHeight', 844)
  Object.assign(viewport, { height: 300, scale: 2 })
  insets(0)
  viewport.dispatchEvent(new Event('resize'))
  expect(root.dataset.keyboard).toBe('0')
  expect(css('--vvh')).toBe('300px')
})

it('does not confuse browser chrome or pinch zoom with IME, but detects a focused browser keyboard', async () => {
  const viewport = Object.assign(new EventTarget(), { height: 400, width: 195, offsetTop: 72, offsetLeft: 16, scale: 2 })
  vi.stubGlobal('innerHeight', 844)
  vi.stubGlobal('innerWidth', 390)
  vi.stubGlobal('visualViewport', viewport)
  wrapper = mount(App, { attachTo: document.body })
  await flushPromises()
  const input = wrapper.get('input')
  input.element.focus()
  viewport.dispatchEvent(new Event('resize'))
  expect(root.dataset.keyboard).toBe('0')
  expect(css('--vvh')).toBe('400px')
  Object.assign(viewport, { scale: 1, height: 380, width: 390, offsetTop: 0, offsetLeft: 0 })
  viewport.dispatchEvent(new Event('resize'))
  expect(root.dataset.keyboard).toBe('1')
  input.element.blur()
  viewport.dispatchEvent(new Event('resize'))
  expect(root.dataset.keyboard).toBe('0')
})
